#!/usr/bin/env node
/**
 * Scans src/templates/* for folders containing both `config.ts` and `index.tsx`
 * and regenerates:
 *   - src/templates/manifest.ts        (ordered list of template ids)
 *   - src/templates/registry.ts        (server registry, static imports)
 *   - src/templates/registry.client.ts (client registry, code-split imports)
 *
 * Adding a template therefore only requires creating the folder — run
 * `npm run templates:registry` (also wired into `dev` and `prebuild`).
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const templatesDir = join(root, "src", "templates");
const manifestFile = join(templatesDir, "manifest.ts");

const IDENTIFIER_RE = /^[a-z][a-z0-9-]*$/;

function discover() {
  if (!existsSync(templatesDir)) return [];
  return readdirSync(templatesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_") && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .filter(
      (name) =>
        existsSync(join(templatesDir, name, "config.ts")) &&
        existsSync(join(templatesDir, name, "index.tsx")),
    )
    .sort();
}

function pascal(id) {
  return id
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function camel(id) {
  const p = pascal(id);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

/** Keeps the previous order for existing ids, appends new ones alphabetically. */
function orderIds(ids) {
  let previous = [];
  if (existsSync(manifestFile)) {
    const source = readFileSync(manifestFile, "utf8");
    previous = [...source.matchAll(/id:\s*"([^"]+)"/g)].map((m) => m[1]);
  }
  const kept = previous.filter((id) => ids.includes(id));
  const added = ids.filter((id) => !kept.includes(id));
  return [...kept, ...added];
}

const ids = discover();
const invalid = ids.filter((id) => !IDENTIFIER_RE.test(id));
if (invalid.length) {
  console.error(`✖ Invalid template folder name(s): ${invalid.join(", ")}. Use kebab-case.`);
  process.exit(1);
}

const ordered = orderIds(ids);

/* --------------------------------- manifest -------------------------------- */

const manifest = `/* AUTO-GENERATED by scripts/generate-registry.mjs — do not edit by hand.
   Run \`npm run templates:registry\` after adding or renaming a template. */

export interface TemplateManifestEntry {
  id: string;
  /** Extensionless path (relative to src/) of the template's index module. */
  module: string;
}

export const TEMPLATE_MANIFEST: TemplateManifestEntry[] = [
${ordered.map((id) => `  { id: "${id}", module: "templates/${id}/index" },`).join("\n")}
];
`;

mkdirSync(templatesDir, { recursive: true });
writeFileSync(manifestFile, manifest, "utf8");

/* ------------------------------ shared pieces ----------------------------- */

const configImports = ordered
  .map((id) => `import { config as ${camel(id)}Config } from "./${id}/config";`)
  .join("\n");

const templateImports = ordered
  .map((id) => `import { Template as ${pascal(id)} } from "./${id}/index";`)
  .join("\n");

const entryPairs = ordered
  .map((id) => `  { config: ${camel(id)}Config, Template: ${pascal(id)} },`)
  .join("\n");

const configArray = ordered.map((id) => `  ${camel(id)}Config,`).join("\n");

/* ------------------------------ server registry --------------------------- */

const serverRegistry = `import type { ComponentType } from "react";
import { TEMPLATE_MANIFEST } from "./manifest";
import type { TemplateCategory, TemplateConfig, TemplateProps } from "./types";

/* AUTO-GENERATED by scripts/generate-registry.mjs — do not edit by hand. */

${configImports}

${templateImports}

interface RegistryEntry {
  config: TemplateConfig;
  Template: ComponentType<TemplateProps>;
}

const ENTRIES: RegistryEntry[] = [
${entryPairs}
];

const BY_ID = new Map(ENTRIES.map((entry) => [entry.config.id, entry]));

export function listTemplates(): TemplateConfig[] {
  const order = TEMPLATE_MANIFEST.map((entry) => entry.id);
  return ENTRIES.map((entry) => entry.config).sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));
}

export function getTemplateConfig(id: string | null | undefined): TemplateConfig | undefined {
  return id ? BY_ID.get(id)?.config : undefined;
}

export function getTemplateConfigOrFallback(id: string | null | undefined): TemplateConfig {
  return getTemplateConfig(id) ?? ENTRIES[0].config;
}

export function getTemplateEntry(id: string | null | undefined): RegistryEntry {
  return (id ? BY_ID.get(id) : undefined) ?? ENTRIES[0];
}

export function getTemplateComponent(id: string | null | undefined): ComponentType<TemplateProps> {
  return getTemplateEntry(id).Template;
}

export function templatesByCategory(): Record<TemplateCategory, TemplateConfig[]> {
  const groups: Record<TemplateCategory, TemplateConfig[]> = {
    Modern: [],
    Creative: [],
    Minimal: [],
    Professional: [],
    Tech: [],
    Academic: [],
    Executive: [],
  };
  for (const config of listTemplates()) groups[config.category].push(config);
  return groups;
}

export function templateCount() {
  return ENTRIES.length;
}

export * from "./types";
`;

writeFileSync(join(templatesDir, "registry.ts"), serverRegistry, "utf8");

/* ------------------------------ client registry --------------------------- */

const loaders = ordered
  .map((id) => `  "${id}": () => import("./${id}/index"),`)
  .join("\n");

const clientRegistry = `import type { ComponentType } from "react";
import dynamic from "next/dynamic";
import { TEMPLATE_MANIFEST } from "./manifest";
import type { TemplateCategory, TemplateConfig, TemplateProps } from "./types";

/* AUTO-GENERATED by scripts/generate-registry.mjs — do not edit by hand.
   Template metadata ships in the main bundle; template code is code-split and
   only downloaded when a CV actually renders. */

${configImports}

export const TEMPLATE_CONFIGS: TemplateConfig[] = [
${configArray}
];

const CONFIG_BY_ID = new Map(TEMPLATE_CONFIGS.map((item) => [item.id, item]));

type Loader = () => Promise<{
  Template?: ComponentType<TemplateProps>;
  default?: ComponentType<TemplateProps>;
}>;

const LOADERS: Record<string, Loader> = {
${loaders}
};

/**
 * One dynamic component per template, created on first use and reused after.
 * Caching keeps the component identity stable across renders, which avoids
 * remounting (and re-fetching) the template on every parent update.
 */
const COMPONENT_CACHE = new Map<string, ComponentType<TemplateProps>>();

function resolvedId(id: string | null | undefined) {
  return getTemplateConfig(id)?.id ?? TEMPLATE_CONFIGS[0].id;
}

export function listTemplates(): TemplateConfig[] {
  const order = TEMPLATE_MANIFEST.map((entry) => entry.id);
  return [...TEMPLATE_CONFIGS].sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));
}

export function getTemplateConfig(id: string | null | undefined): TemplateConfig | undefined {
  return id ? CONFIG_BY_ID.get(id) : undefined;
}

export function getTemplateConfigOrFallback(id: string | null | undefined): TemplateConfig {
  return getTemplateConfig(id) ?? TEMPLATE_CONFIGS[0];
}

export function getTemplateComponent(id: string | null | undefined): ComponentType<TemplateProps> {
  const target = resolvedId(id);
  const loader = LOADERS[target];
  if (!loader) {
    throw new Error(\`Template "\${target}" is missing from registry.client.ts\`);
  }
  const cached = COMPONENT_CACHE.get(target);
  if (cached) return cached;

  // \`ssr: false\`: templates are code-split and browser-only. They rely on
  // measured geometry, so rendering them on the server would risk a hydration
  // mismatch. The renderer shows a light A4 placeholder until the chunk lands.
  const component = dynamic(
    () => loader().then((mod) => (mod.Template ?? mod.default) as ComponentType<TemplateProps>),
    { ssr: false },
  );
  COMPONENT_CACHE.set(target, component);
  return component;
}

export function templatesByCategory(): Record<TemplateCategory, TemplateConfig[]> {
  const groups: Record<TemplateCategory, TemplateConfig[]> = {
    Modern: [],
    Creative: [],
    Minimal: [],
    Professional: [],
    Tech: [],
    Academic: [],
    Executive: [],
  };
  for (const template of listTemplates()) groups[template.category].push(template);
  return groups;
}

export function templateCount() {
  return TEMPLATE_CONFIGS.length;
}

export * from "./types";
`;

writeFileSync(join(templatesDir, "registry.client.ts"), clientRegistry, "utf8");

console.log(
  `✔ registries updated — ${ordered.length} template(s): ${ordered.join(", ") || "none"}`,
);
